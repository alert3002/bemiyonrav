const I18nContext = createContext(null)

export function translate(lang, key, vars) {
  let text = STRINGS[lang]?.[key] ?? STRINGS.ru[key] ?? key
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.split(`{${name}}`).join(String(value))
    })
  }
  return text
}

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('ru')
  useEffect(() => {
    AsyncStorage.getItem('bemiyona_lang').then((saved) => {
      if (saved === 'ru' || saved === 'tj' || saved === 'zh') setLangState(saved)
    }).catch(() => {})
  }, [])
  const setLang = (value) => {
    const next = ['ru', 'tj', 'zh'].includes(value) ? value : 'ru'
    AsyncStorage.setItem('bemiyona_lang', next).catch(() => {})
    setLangState(next)
  }
  const t = (key, vars) => translate(lang, key, vars)
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

export function errorText(error, t) {
  const code = error?.code
  if (code) {
    const text = t(code, error.body)
    if (text !== code) return text
  }
  const detail = typeof error?.body?.detail === 'string'
    ? error.body.detail.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim()
    : ''
  if (detail && detail.length < 160 && !/server error|<!doctype|<html/i.test(detail)) return detail
  return t('error')
}
